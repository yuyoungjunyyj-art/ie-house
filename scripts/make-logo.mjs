// Cuts the pressed-ink mark out of Photo/The Ie Logo.png for the header.
// Dark ink becomes opaque and paper becomes transparent, so the header can colour it for either theme.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import sharp from 'sharp';

const root = fileURLToPath(new URL('..', import.meta.url));
const source = join(root, 'Photo/The Ie Logo.png');
const height = 120;

// The wordmark "The Ie" sits below the mark, from about y = 1400.
const mark = await sharp(source).extract({ left: 0, top: 0, width: 2048, height: 1340 }).png().toBuffer();
const { data, info } = await sharp(mark).trim({ threshold: 40 }).resize({ height }).greyscale().raw().toBuffer({ resolveWithObject: true });

const pixels = Buffer.alloc(info.width * info.height * 4);
for (let i = 0; i < data.length; i += 1) {
  pixels[i * 4 + 3] = 255 - data[i];
}
const png = await sharp(pixels, { raw: { width: info.width, height: info.height, channels: 4 } })
  .png({ compressionLevel: 9, palette: false })
  .toBuffer();

const uri = `data:image/png;base64,${png.toString('base64')}`;
writeFileSync(join(root, 'src/lib/logo-ink.ts'), `// Generated by scripts/make-logo.mjs.\nexport const logoInk = '${uri}';\nexport const logoRatio = '${info.width} / ${info.height}';\n`);
console.log(`Logo written: ${info.width}x${info.height}, ${(png.length / 1024).toFixed(1)} KB.`);
